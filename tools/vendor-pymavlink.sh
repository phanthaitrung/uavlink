#!/usr/bin/env bash
# Rebuilds vendor/pymavlink/ and vendor/README.md from the pymavlink 2.4.50 wheel on PyPI.
# Needs Internet and python3-pip; the package build itself never does (the result is committed).
# The wheel is platform specific only because of compiled extras: the .py files we keep are identical on every platform,
# so one wheel is pinned (cp312 manylinux x86_64) and checked against its sha256.
# Usage: bash tools/vendor-pymavlink.sh
set -euo pipefail

version=2.4.50
wheel_sha256=570d22774bc7e53f55a637f46b9defa78321924c6a2e50a5790fb22b0e6a0709
wheel="pymavlink-$version-cp312-cp312-manylinux2014_x86_64.manylinux_2_17_x86_64.manylinux_2_28_x86_64.whl"
# Runtime files only: mavutil + the ArduPilot MAVLink 2 dialect. Pure Python, no compiled module.
files=(
  __init__.py
  mavutil.py
  mavexpression.py
  mavextra.py
  quaternion.py
  rotmat.py
  generator/__init__.py
  generator/mavcrc.py
  generator/mavparse.py
  dialects/__init__.py
  dialects/v20/__init__.py
  dialects/v20/ardupilotmega.py
)

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

python3 -m pip download --no-deps --only-binary=:all: --implementation cp --python-version 3.12 --abi cp312 \
  --platform manylinux2014_x86_64 -d "$work" "pymavlink==$version" >/dev/null
actual="$(sha256sum "$work/$wheel" | cut -d' ' -f1)"
if [ "$actual" != "$wheel_sha256" ]; then
  echo "sha256 mismatch for $wheel: got $actual, expected $wheel_sha256" >&2
  exit 1
fi

python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$work/$wheel" "$work/x"

out="$here/vendor/pymavlink"
rm -rf "$out"
mkdir -p "$out"
for f in "${files[@]}"; do
  mkdir -p "$out/$(dirname "$f")"
  cp "$work/x/pymavlink/$f" "$out/$f"
done
cp "$work/x/pymavlink-$version.dist-info/licenses/COPYING" "$out/COPYING"
# The one local change: default to MAVLink 2 and the vendored dialect, so a bare "import pymavlink.mavutil" works.
cat >> "$out/__init__.py" <<'PY'

# uavlink: vendored copy ships only the MAVLink 2 ardupilotmega dialect; select it unless the caller chose another.
import os as _os
_os.environ.setdefault("MAVLINK20", "1")
_os.environ.setdefault("MAVLINK_DIALECT", "ardupilotmega")
PY
# Keep the checkout LF-only whatever the wheel used.
find "$out" -type f -exec sed -i 's/\r$//' {} +

{
  echo "# Vendored code"
  echo
  echo "Generated by \`tools/vendor-pymavlink.sh\`; do not edit by hand."
  echo
  echo "## pymavlink $version"
  echo
  echo "- Source: https://pypi.org/project/pymavlink/$version/ (https://github.com/ArduPilot/pymavlink)"
  echo "- Archive: \`$wheel\`"
  echo "- sha256: \`$wheel_sha256\`"
  echo "- License: LGPL-3 for the library, MIT for the generated dialect code; see \`pymavlink/COPYING\`"
  echo "- Pure Python, nothing compiled. \`fastcrc\` is optional (not vendored), \`lxml\` and \`future\` are not needed at runtime."
  echo "- Dialect: only \`ardupilotmega\` (MAVLink 2). One local change: \`pymavlink/__init__.py\` ends with two \`os.environ.setdefault\` lines"
  echo "  (\`MAVLINK20=1\`, \`MAVLINK_DIALECT=ardupilotmega\`) so a bare import works; the default dialect \`all\` is not vendored."
  echo "- Use: put this \`vendor/\` directory on \`PYTHONPATH\`. Needs only Ubuntu's \`python3\` and \`python3-serial\`."
  echo
  echo "Files (relative to \`vendor/pymavlink/\`):"
  echo
  echo "| File | sha256 |"
  echo "|---|---|"
  (cd "$out" && for f in COPYING "${files[@]}"; do echo "| \`$f\` | \`$(sha256sum "$f" | cut -d' ' -f1)\` |"; done)
} > "$here/vendor/README.md"

echo "vendored pymavlink $version into vendor/pymavlink (${#files[@]} files + COPYING)"
